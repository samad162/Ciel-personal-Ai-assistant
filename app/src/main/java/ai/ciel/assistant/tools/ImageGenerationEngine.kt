package ai.ciel.assistant.tools

import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.net.Uri
import android.os.Environment
import android.util.Base64
import android.util.Log
import androidx.core.content.FileProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import okhttp3.Request
import java.io.ByteArrayOutputStream
import java.io.File
import java.io.FileOutputStream
import java.net.URLEncoder
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.concurrent.TimeUnit

data class GeneratedImageResult(
    val file: File,
    val uri: Uri,
    val bitmap: Bitmap?,
    val prompt: String,
    val imageUrl: String
)

/**
 * Multimodal AI & Real Image Generation Engine:
 * Generates genuine high-definition illustrations, concept art, and diagrams from text prompts.
 * Persists images to device storage, generates shareable FileProvider URIs,
 * and handles base64 image encoding for Vision-capable LLMs.
 */
class ImageGenerationEngine(private val context: Context) {

    private val tag = "CielImageEngine"

    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .build()

    suspend fun generateImage(prompt: String): GeneratedImageResult? = withContext(Dispatchers.IO) {
        val cleanPrompt = prompt.trim()
        val encodedPrompt = URLEncoder.encode(cleanPrompt, "UTF-8")
        val imageUrl = "https://image.pollinations.ai/prompt/$encodedPrompt?width=768&height=768&nologo=true&model=flux"

        Log.i(tag, "Generating image for prompt: '$cleanPrompt' via $imageUrl")

        try {
            val request = Request.Builder()
                .url(imageUrl)
                .header("User-Agent", "Mozilla/5.0 (Android; Mobile; CIEL-AI/2.0)")
                .build()

            val response = client.newCall(request).execute()
            if (response.isSuccessful) {
                val bytes = response.body?.bytes()
                if (bytes != null && bytes.isNotEmpty()) {
                    val bitmap = BitmapFactory.decodeByteArray(bytes, 0, bytes.size)

                    val picturesDir = context.getExternalFilesDir(Environment.DIRECTORY_PICTURES) ?: context.cacheDir
                    if (!picturesDir.exists()) picturesDir.mkdirs()

                    val timestamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault()).format(Date())
                    val sanitizedName = cleanPrompt.replace(Regex("[^a-zA-Z0-9]"), "_").take(20)
                    val outputFile = File(picturesDir, "ciel_${sanitizedName}_$timestamp.jpg")

                    FileOutputStream(outputFile).use { out ->
                        out.write(bytes)
                        out.flush()
                    }

                    val uri = FileProvider.getUriForFile(context, "ai.ciel.assistant.fileprovider", outputFile)
                    Log.i(tag, "Successfully generated and saved image: ${outputFile.absolutePath}")

                    return@withContext GeneratedImageResult(
                        file = outputFile,
                        uri = uri,
                        bitmap = bitmap,
                        prompt = cleanPrompt,
                        imageUrl = imageUrl
                    )
                }
            } else {
                Log.w(tag, "Image API returned HTTP ${response.code}")
            }
        } catch (e: Exception) {
            Log.e(tag, "Image generation error: ${e.message}", e)
        }
        return@withContext null
    }

    fun shareImage(result: GeneratedImageResult) {
        try {
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "image/jpeg"
                putExtra(Intent.EXTRA_STREAM, result.uri)
                putExtra(Intent.EXTRA_TEXT, "Generated by CIEL AI: \"${result.prompt}\"")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            val chooser = Intent.createChooser(intent, "Share Image via").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)
        } catch (e: Exception) {
            Log.e(tag, "Could not share image: ${e.message}")
        }
    }

    companion object {
        /**
         * Compress and encode a Bitmap to base64 JPEG format for Multimodal Vision API processing.
         * Scales down resolution to preserve memory on 4 GB RAM devices.
         */
        fun encodeBitmapToBase64(bitmap: Bitmap, maxDimension: Int = 720): String {
            val width = bitmap.width
            val height = bitmap.height
            val scale = if (width > maxDimension || height > maxDimension) {
                val max = Math.max(width, height)
                maxDimension.toFloat() / max
            } else 1.0f

            val scaled = if (scale < 1.0f) {
                Bitmap.createScaledBitmap(bitmap, (width * scale).toInt(), (height * scale).toInt(), true)
            } else bitmap

            val outputStream = ByteArrayOutputStream()
            scaled.compress(Bitmap.CompressFormat.JPEG, 80, outputStream)
            val byteArray = outputStream.toByteArray()
            return Base64.encodeToString(byteArray, Base64.NO_WRAP)
        }
    }
}
